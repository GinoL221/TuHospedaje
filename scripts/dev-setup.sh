#!/usr/bin/env bash
# Create deploy/dev.env for the Docker Compose development stack with demo data.
# Generates random database passwords and Base64 secrets, plus bcrypt hashes of
# the documented demo passwords. Nothing generated here is committed.
#
# Usage: scripts/dev-setup.sh [--force]
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
TARGET=${DEV_SETUP_TARGET:-"$ROOT/deploy/dev.env"}
ADMIN_EMAIL=admin@tuhospedaje.com
ADMIN_PASSWORD=Admin1234
GUEST_EMAIL=huesped@tuhospedaje.com
GUEST_PASSWORD=Huesped1234
HASHER_IMAGE=httpd:2.4-alpine

force=0
case "${1:-}" in
  "") ;;
  --force) force=1 ;;
  *)
    echo "usage: scripts/dev-setup.sh [--force]" >&2
    exit 2
    ;;
esac
if [ "$#" -gt 1 ]; then
  echo "usage: scripts/dev-setup.sh [--force]" >&2
  exit 2
fi

if [ -e "$TARGET" ] && [ "$force" -eq 0 ]; then
  echo "deploy/dev.env already exists; rerun with --force to replace it" >&2
  exit 1
fi

random_base64() {
  head -c 48 /dev/urandom | base64 | tr -d '\n'
}

random_hex() {
  head -c 16 /dev/urandom | od -An -tx1 | tr -d ' \n'
}

# Print a bcrypt hash (cost 10) of $1 using htpasswd, from the host or from Docker.
bcrypt_hash() {
  local output
  if command -v htpasswd > /dev/null 2>&1; then
    output=$(htpasswd -nbBC 10 "" "$1" 2> /dev/null) || output=""
  elif command -v docker > /dev/null 2>&1; then
    if ! docker image inspect "$HASHER_IMAGE" > /dev/null 2>&1; then
      echo "Pulling $HASHER_IMAGE to compute bcrypt hashes..." >&2
      docker pull --quiet "$HASHER_IMAGE" > /dev/null || true
    fi
    output=$(docker run --rm --pull=never "$HASHER_IMAGE" htpasswd -nbBC 10 "" "$1" 2> /dev/null) || output=""
  else
    output=""
  fi
  output=$(printf %s "$output" | tr -d ':\r\n')
  # Dollar signs belong to the grep expression, not shell expansion.
  # shellcheck disable=SC2016
  if ! printf %s "$output" | LC_ALL=C grep -Eq '^\$2[aby]\$1[0-4]\$[./A-Za-z0-9]{53}$'; then
    echo "could not generate a bcrypt hash: install htpasswd (apache2-utils) or start Docker" >&2
    return 1
  fi
  printf %s "$output"
}

admin_hash=$(bcrypt_hash "$ADMIN_PASSWORD") || exit 1
guest_hash=$(bcrypt_hash "$GUEST_PASSWORD") || exit 1

tmp=$(mktemp "$(dirname "$TARGET")/.dev.env.XXXXXX")
trap 'rm -f "$tmp"' EXIT
chmod 600 "$tmp"
cat > "$tmp" <<EOF
# Generated by scripts/dev-setup.sh for local development only. Do not commit.
DEV_DB_NAME=tuhospedaje_dev
DEV_DB_USERNAME=tuhospedaje_dev
DEV_DB_PASSWORD=$(random_hex)
DEV_DB_ROOT_PASSWORD=$(random_hex)
DEV_JWT_SECRET=$(random_base64)
DEV_SESSION_REFRESH_KEY=$(random_base64)

# Demo accounts loaded by compose.dev-seed.yaml on the first start of an empty database:
# $ADMIN_EMAIL / $ADMIN_PASSWORD (ADMIN) and $GUEST_EMAIL / $GUEST_PASSWORD (USER).
# Only the seed entrypoint reads these hashes, straight from this file. Single quotes
# keep Compose from interpolating the '\$' signs when this file is the --env-file.
DEV_ADMIN_PASSWORD_HASH='$admin_hash'
DEV_GUEST_PASSWORD_HASH='$guest_hash'
EOF
mv "$tmp" "$TARGET"
trap - EXIT

echo "Created deploy/dev.env"
echo "Demo admin: $ADMIN_EMAIL / $ADMIN_PASSWORD"
echo "Demo guest: $GUEST_EMAIL / $GUEST_PASSWORD"
